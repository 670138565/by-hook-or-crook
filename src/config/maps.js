/* =====================================================================
 * 地图配置（maps.js）
 * =====================================================================
 * 作用：集中存放所有地图的属性。以后加新地图，只需要在这里加一条配置，
 *       再把地图图片放到 assets/images/maps/ 即可，不用改其他代码。
 *
 * 每条地图配置包含：
 *   key    : 地图唯一代号（代码里用这个引用，英文，避免编码问题）
 *   name   : 地图中文名（界面上显示给玩家看）
 *   image  : 地图图片路径
 *   width  : 原图宽度（像素）
 *   height : 原图高度（像素）
 *   scale  : 显示缩放（0.6=缩小到60%），游戏世界大小 = 原图×缩放
 *
 * 通俗讲：这是"地图档案册"。PreloadScene 会自动加载这里所有地图的图片，
 *        GameScene 根据地图代号读取档案来铺图、设置边界。
 * ===================================================================== */
