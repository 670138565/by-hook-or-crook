/* =====================================================================
 * 事件总线（EventBus.js）
 * =====================================================================
 * 作用：让游戏里不同的模块能"互相喊话"，但不直接认识对方。
 *
 * 为什么需要它？举个例子：
 *   - 玩家偷东西失败 → 要通知"守卫系统"开始追捕
 *   - 如果直接写 Player 调用 Guard，那 Player 就依赖 Guard 了，
 *     将来改 Guard 容易把 Player 弄坏。
 *   - 用事件总线：Player 只管喊一声 "偷窃失败了"，
 *     谁关心谁就监听这个事件，Player 不需要知道有谁在听。
 *
 * 通俗讲：像一个广播站。模块 A 喊话（emit），所有订阅了的模块 B/C/D 都能听到。
 * 这样模块之间解耦，加新功能/删旧功能都不会互相牵连。
 *
 * 用法：
 *   发消息：EventBus.emit('偷窃失败', { 目标: '商人' })
 *   收消息：EventBus.on('偷窃失败', (data) => { ... })
 * ===================================================================== */
window.EventBus = new Phaser.Events.EventEmitter();
